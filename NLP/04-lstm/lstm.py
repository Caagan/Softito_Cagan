class IMDBPyTorchLSTMClassifier(nn.Module):
    """
    Dizi (Kelime İndeksleri) → Etiket Sınıflandırması.
    Mimari: Girdi → Embedding (Kelime Vektörü) → LSTM (2 Katman) → Dropout → Linear → Sınıf
    """

    def __init__(self, vocab_size, embedding_dim, hidden_size, num_classes=2,
                 num_layers=2, dropout=0.3):
        """
        super().__init__() zorunluluğu:
        → nn.Module'ün iç kayıt defterini kurar ve parametreleri izlenebilir kılar.
        """
        super().__init__()

        # 1. Metin Projeleri İçin Gerekli Embedding Katmanı
        # Kelime ID'lerini yoğun anlamsal vektörlere dönüştürür.
        self.embedding = nn.Embedding(num_embeddings=vocab_size, embedding_dim=embedding_dim)

        # 2. PyTorch Hazır LSTM Katmanı
        self.lstm = nn.LSTM(
            input_size  = embedding_dim, # LSTM girdisi artık embedding vektör boyutudur
            hidden_size = hidden_size,
            num_layers  = num_layers,
            batch_first = True,          # Girdi düzeni: (batch, seq, feat)
            dropout     = dropout if num_layers > 1 else 0,
        )

        # 3. Dropout Katmanı (Aşırı öğrenmeyi - Overfitting engellemek için)
        self.dropout = nn.Dropout(dropout)

        # 4. Tam Bağlı (Linear) Çıkış Katmanı
        # Son zaman adımındaki özet bilgiyi (hidden_size) alıp sınıf skorlarına dönüştürür.
        self.fc = nn.Linear(hidden_size, num_classes)

    def forward(self, x):
        """
        İleri geçiş adımları.
        x : (batch_size, seq_len) -> Kelime indeks matrisi
        """
        # x: (batch_size, seq_len) → embedded: (batch_size, seq_len, embedding_dim)
        embedded = self.embedding(x)
        embedded = self.dropout(embedded)

        # output: (batch, seq_len, hidden) -> her adımın h_t'si
        # h_n   : (num_layers, batch, hidden) -> son zaman adımındaki gizli durumlar
        output, (h_n, c_n) = self.lstm(embedded)

        # h_n[-1]: en üstteki (son) LSTM katmanının son zaman adımındaki durumu.
        # Bu vektör tüm cümleyi özetleyen ana yapıdır. Şekil: (batch_size, hidden_size)
        last_hidden = h_n[-1]

        # Eğitim modunda nöronları rastgele söndürür
        last_hidden = self.dropout(last_hidden)

        # Ham sınıf skorları (Logits): (batch_size, num_classes)
        logits = self.fc(last_hidden)
        return logits

    def get_all_hidden(self, x):
        """Tüm adımların h_t'sini döndürür (ileride analiz yapmak istersen)."""
        with torch.no_grad():
            embedded = self.embedding(x)
            output, (h_n, c_n) = self.lstm(embedded)
        return output, h_n, c_n


