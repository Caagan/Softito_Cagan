def sigmoid(x):
    """Sigmoid aktivasyon fonksiyonu. Değerleri [0, 1] arasına sıkıştırır."""
    return 1 / (1 + np.exp(-x))

class IMDBVanillaLSTMClassifier:
    """
    Sıfırdan NumPy ile yazılmış IMDB Duygu Analizi Sınıflandırıcısı.
    Toplu veri (Batch) işlemeyi ve kapı analizlerini çıkarmayı destekler.
    """

    def __init__(self, input_size: int, hidden_size: int, num_classes: int = 2):
        """
        Parametreler:
            input_size  (D): Her kelimenin embedding (vektör) boyutu
            hidden_size (H): LSTM'in iç hafıza boyutu
            num_classes (C): Sınıf sayısı (IMDB için 2: Pozitif/Negatif)
        """
        rng = np.random.default_rng(42)
        H, D = hidden_size, input_size
        scale = 0.1

        # ── 4 Kapı Ağırlık Matrisleri (H, H+D) ──────────────────────────
        self.W_f = rng.standard_normal((H, H + D)) * scale
        self.W_i = rng.standard_normal((H, H + D)) * scale
        self.W_g = rng.standard_normal((H, H + D)) * scale
        self.W_o = rng.standard_normal((H, H + D)) * scale

        # ── Bias Vektörleri (H,) ─────────────────────────────────────────
        self.b_f = np.ones(H)    # Hafızayı korumak için 1.0 ile başlıyoruz
        self.b_i = np.zeros(H)
        self.b_g = np.zeros(H)
        self.b_o = np.zeros(H)

        # ── Sınıflandırma (Linear / FC) Katmanı Ağırlıkları ──────────────
        self.W_fc = rng.standard_normal((num_classes, H)) * scale
        self.b_fc = np.zeros(num_classes)

        self.hidden_size = H
        self.input_size  = D
        self.num_classes = num_classes

    def _concat(self, h_prev, x_t):
        """Batch uyumlu yan yana birleştirme: (batch_size, H) + (batch_size, D) → (batch_size, H+D)"""
        return np.concatenate([h_prev, x_t], axis=1)

    def forward_step(self, x_t, h_prev, c_prev):
        """Tüm Batch için TEK bir zaman adımını işler."""
        combined = self._concat(h_prev, x_t)

        # Kapı Hesaplamaları: (batch_size, H+D) @ (H+D, H) → (batch_size, H)
        f_t = sigmoid(combined @ self.W_f.T + self.b_f)
        i_t = sigmoid(combined @ self.W_i.T + self.b_i)
        g_t = np.tanh(combined @ self.W_g.T + self.b_g)
        o_t = sigmoid(combined @ self.W_o.T + self.b_o)

        # Hücre ve Gizli durum güncellemeleri
        c_t = f_t * c_prev + i_t * g_t
        h_t = o_t * np.tanh(c_t)

        gates = {"f": f_t, "i": i_t, "g": g_t, "o": o_t}
        return h_t, c_t, gates

    def forward_sequence(self, X):
        """Tam bir veri paketini (Batch) baştan sona işler ve tüm adımları kaydeder."""
        batch_size, seq_len, _ = X.shape

        h = np.zeros((batch_size, self.hidden_size))
        c = np.zeros((batch_size, self.hidden_size))

        H_list, C_list, gates_list = [], [], []

        for t in range(seq_len):
            x_t = X[:, t, :]
            h, c, gates = self.forward_step(x_t, h, c)
            H_list.append(h.copy())
            C_list.append(c.copy())
            gates_list.append(gates)

        # Sınıflandırma katmanından geçiş (Sadece en son adımın h_t'si kullanılır)
        logits = h @ self.W_fc.T + self.b_fc

        # Matplotlib görselleştirmesi için şekilleri (seq_len, batch_size, hidden_size) formatına getiriyoruz
        return logits, np.array(H_list), np.array(C_list), gates_list

