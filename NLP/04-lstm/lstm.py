"""## 2. IMDBPyTorchLSTMClassifier Modelini Uygulama ve Eğitme

Şimdi `er47jQpk4rmV` hücresinde tanımladığınız `IMDBPyTorchLSTMClassifier` modelini gerçek veri üzerinde eğiteceğiz.

### 2.1 Model Eğitim ve Değerlendirme Fonksiyonları

Modeli eğitmek ve her epoch sonunda performansını değerlendirmek için fonksiyonlar oluşturalım.
"""

def train(model, dataloader, criterion, optimizer, device):
    model.train() # Modeli eğitim moduna al
    total_loss = 0
    correct_predictions = 0
    total_samples = 0

    for batch_x, batch_y in tqdm(dataloader, desc="Eğitim"): # `tqdm` import edildi
        batch_x, batch_y = batch_x.to(device), batch_y.to(device)

        optimizer.zero_grad() # Gradyanları sıfırla
        outputs = model(batch_x) # Modelden tahmin al
        loss = criterion(outputs, batch_y) # Kaybı hesapla
        loss.backward() # Geri yayılım
        optimizer.step() # Parametreleri güncelle

        total_loss += loss.item()
        _, predicted = torch.max(outputs.data, 1) # Tahmin edilen sınıfı al
        total_samples += batch_y.size(0)
        correct_predictions += (predicted == batch_y).sum().item()

    avg_loss = total_loss / len(dataloader)
    accuracy = correct_predictions / total_samples
    return avg_loss, accuracy

def evaluate(model, dataloader, criterion, device):
    model.eval() # Modeli değerlendirme moduna al (dropout vb. kapatır)
    total_loss = 0
    correct_predictions = 0
    total_samples = 0

    with torch.no_grad(): # Gradyan hesaplamayı kapat
        for batch_x, batch_y in tqdm(dataloader, desc="Değerlendirme"): # `tqdm` import edildi
            batch_x, batch_y = batch_x.to(device), batch_y.to(device)

            outputs = model(batch_x)
            loss = criterion(outputs, batch_y)

            total_loss += loss.item()
            _, predicted = torch.max(outputs.data, 1)
            total_samples += batch_y.size(0)
            correct_predictions += (predicted == batch_y).sum().item()

    avg_loss = total_loss / len(dataloader)
    accuracy = correct_predictions / total_samples
    return avg_loss, accuracy

