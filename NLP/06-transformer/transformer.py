import torch
import torch.nn as nn
import torch.nn.functional as F
import math
import matplotlib.pyplot as plt

class PositionalEncoding(nn.Module):
    """Pozisyonel kodlama modülü - Dizi sırasını modele öğretir."""
    def __init__(self, d_model, max_len=5000):
        super().__init__()
        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, d_model, 2).float() * (-math.log(10000.0) / d_model))
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        self.register_buffer("pe", pe.unsqueeze(0))

    def forward(self, x):
        return x + self.pe[:, : x.size(1), :]


class MultiHeadAttention(nn.Module):
    """Çok başlı dikkat mekanizması - Kelimeler arası ilişkileri kurar."""
    def __init__(self, d_model, num_heads):
        super().__init__()
        assert d_model % num_heads == 0, "d_model baş sayısına tam bölünmeli!"
        self.d_model = d_model
        self.num_heads = num_heads
        self.d_k = d_model // num_heads

        self.W_q = nn.Linear(d_model, d_model)
        self.W_k = nn.Linear(d_model, d_model)
        self.W_v = nn.Linear(d_model, d_model)
        self.W_o = nn.Linear(d_model, d_model)

    def split_heads(self, x):
        batch_size, seq_len, _ = x.size()
        return x.view(batch_size, seq_len, self.num_heads, self.d_k).transpose(1, 2)

    def combine_heads(self, x):
        batch_size, _, seq_len, _ = x.size()
        return x.transpose(1, 2).contiguous().view(batch_size, seq_len, self.d_model)

    def forward(self, query, key, value, mask=None):
        Q = self.split_heads(self.W_q(query))
        K = self.split_heads(self.W_k(key))
        V = self.split_heads(self.W_v(value))

        scores = torch.matmul(Q, K.transpose(-2, -1)) / math.sqrt(self.d_k)
        if mask is not None:
            scores = scores.masked_fill(mask == 0, float("-inf"))

        attn = F.softmax(scores, dim=-1)
        context = torch.matmul(attn, V)
        output = self.W_o(self.combine_heads(context))
        return output, attn


class PositionwiseFeedForward(nn.Module):
    """Pozisyon bazlı ileri beslemeli ağ - Özellikleri doğrusal olmayan şekilde işler."""
    def __init__(self, d_model, d_ff, dropout=0.1):
        super().__init__()
        self.linear1 = nn.Linear(d_model, d_ff)
        self.linear2 = nn.Linear(d_ff, d_model)
        self.dropout = nn.Dropout(dropout)

    def forward(self, x):
        return self.linear2(self.dropout(F.gelu(self.linear1(x))))


class EncoderLayer(nn.Module):
    """Tek bir Encoder Katmanı."""
    def __init__(self, d_model, num_heads, d_ff, dropout=0.1):
        super().__init__()
        self.self_attn = MultiHeadAttention(d_model, num_heads)
        self.feed_forward = PositionwiseFeedForward(d_model, d_ff, dropout)
        self.norm1 = nn.LayerNorm(d_model)
        self.norm2 = nn.LayerNorm(d_model)
        self.dropout = nn.Dropout(dropout)

    def forward(self, x, mask=None):
        # Pre-Layer Normalization for self-attention
        _x = self.norm1(x)
        attn_out, _ = self.self_attn(_x, _x, _x, mask)
        x = x + self.dropout(attn_out) # Add residual after attention

        # Pre-Layer Normalization for feed-forward
        _x = self.norm2(x)
        ff_out = self.feed_forward(_x)
        x = x + self.dropout(ff_out) # Add residual after feed-forward
        return x


class DecoderLayer(nn.Module):
    """Tek bir Decoder Katmanı."""
    def __init__(self, d_model, num_heads, d_ff, dropout=0.1):
        super().__init__()
        self.self_attn = MultiHeadAttention(d_model, num_heads)
        self.cross_attn = MultiHeadAttention(d_model, num_heads)
        self.feed_forward = PositionwiseFeedForward(d_model, d_ff, dropout)
        self.norm1 = nn.LayerNorm(d_model)
        self.norm2 = nn.LayerNorm(d_model)
        self.norm3 = nn.LayerNorm(d_model)
        self.dropout = nn.Dropout(dropout)

    def forward(self, x, enc_output, src_mask=None, tgt_mask=None):
        # Pre-Layer Normalization for self-attention
        _x = self.norm1(x)
        attn_out, _ = self.self_attn(_x, _x, _x, tgt_mask)
        x = x + self.dropout(attn_out)

        # Pre-Layer Normalization for cross-attention
        _x = self.norm2(x)
        cross_out, _ = self.cross_attn(_x, enc_output, enc_output, src_mask)
        x = x + self.dropout(cross_out)

        # Pre-Layer Normalization for feed-forward
        _x = self.norm3(x)
        ff_out = self.feed_forward(_x)
        x = x + self.dropout(ff_out)
        return x


class Transformer(nn.Module):
    """Tam Transformer Modeli (Encoder-Decoder)"""
    def __init__(self, src_vocab_size, tgt_vocab_size, d_model=512, num_heads=8,
                 num_layers=6, d_ff=2048, max_len=100, dropout=0.1):
        super().__init__()
        self.encoder_embedding = nn.Embedding(src_vocab_size, d_model)
        self.decoder_embedding = nn.Embedding(tgt_vocab_size, d_model)
        self.positional_encoding = PositionalEncoding(d_model, max_len)

        self.encoder_layers = nn.ModuleList(
            [EncoderLayer(d_model, num_heads, d_ff, dropout) for _ in range(num_layers)]
        )
        self.decoder_layers = nn.ModuleList(
            [DecoderLayer(d_model, num_heads, d_ff, dropout) for _ in range(num_layers)]
        )

        self.fc_out = nn.Linear(d_model, tgt_vocab_size)
        self.dropout = nn.Dropout(dropout)
        self.final_norm = nn.LayerNorm(d_model) # Yeni eklenen final normalizasyon

    def generate_mask(self, src, tgt):
        src_mask = (src != 0).unsqueeze(1).unsqueeze(2)  # (batch, 1, 1, src_len)
        tgt_mask = (tgt != 0).unsqueeze(1).unsqueeze(3)  # (batch, 1, tgt_len, 1)

        seq_len = tgt.size(1)
        nopeak_mask = (1 - torch.triu(torch.ones(1, seq_len, seq_len), diagonal=1)).bool()
        tgt_mask = tgt_mask & nopeak_mask.to(tgt.device)
        return src_mask, tgt_mask

    def encode(self, src, src_mask):
        x = self.dropout(self.positional_encoding(self.encoder_embedding(src)))
        for layer in self.encoder_layers:
            x = layer(x, src_mask)
        return x

    def decode(self, tgt, enc_output, src_mask, tgt_mask):
        x = self.dropout(self.positional_encoding(self.decoder_embedding(tgt)))
        for layer in self.decoder_layers:
            x = layer(x, enc_output, src_mask, tgt_mask)
        return x

    def forward(self, src, tgt):
        src_mask, tgt_mask = self.generate_mask(src, tgt)
        enc_output = self.encode(src, src_mask)
        dec_output = self.decode(tgt, enc_output, src_mask, tgt_mask)
        return self.fc_out(self.final_norm(dec_output)) # Final normalizasyonu uygulandı

VOCAB_SIZE = 30       # Küçük kelime dağarcığı (0-29)
SEQ_LEN = 8           # Üretilecek rastgele sayıların uzunluğu
SOS, EOS, PAD = 1, 2, 0

def make_batch(batch_size=32, seq_len=SEQ_LEN, vocab_size=VOCAB_SIZE):
    """Modelin kopyalamayı öğrenmesi için yapay veri üretir."""
    # 3 ile 29 arasında rastgele sayılar üret (0, 1, 2 özel tokenlar için ayrıldı)
    seq = torch.randint(3, vocab_size, (batch_size, seq_len))
    src = seq

    # Hedef dizinin başına SOS, sonuna EOS ekle
    tgt_full = torch.cat(
        [torch.full((batch_size, 1), SOS), seq, torch.full((batch_size, 1), EOS)], dim=1
    )
    tgt_input = tgt_full[:, :-1]   # Decoder girdisi (SOS ile başlar, EOS içermez)
    tgt_output = tgt_full[:, 1:]   # Gerçek etiket (SOS içermez, EOS ile biter)
    return src, tgt_input, tgt_output

