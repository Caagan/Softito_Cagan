@torch.no_grad()
def greedy_decode(model, src, max_len=SEQ_LEN + 2):
    """Eğitilen modelin adım adım çıktı üretmesini sağlar."""
    model.eval()
    src_mask, _ = model.generate_mask(src, src)
    enc_output = model.encode(src, src_mask)

    # Çıkarıma sadece SOS (Start of Sentence) tokenı ile başla
    ys = torch.full((src.size(0), 1), SOS, dtype=torch.long).to(src.device)

    for _ in range(max_len - 1):
        _, tgt_mask = model.generate_mask(src, ys)
        out = model.decode(ys, enc_output, src_mask, tgt_mask)
        logits = model.fc_out(out[:, -1, :]) # Son üretilen adımın logit'i
        next_token = logits.argmax(dim=-1, keepdim=True) # En yüksek olasılıklı kelimeyi seç
        ys = torch.cat([ys, next_token], dim=1)

        # Eğer üretilen token EOS (End of Sentence) ise üretimi durdurabiliriz (opsiyonel)
        # Bu satır, toplu işlem (batch processing) sırasında 'item()' çağrıldığında hataya neden oluyordu.
        # 'max_len' zaten maksimum uzunluğu sınırladığı için kaldırıldı.

    return ys

