def evaluate_model(model, num_test_batches=100, batch_size=32):
    model.eval() # Modeli değerlendirme moduna al
    correct_predictions = 0
    total_predictions = 0

    print("\nModel test ediliyor...")

    for _ in range(num_test_batches):
        src_test, _, tgt_output_test = make_batch(batch_size=batch_size) # Test verisi oluştur

        # Tahminleri al
        predictions = greedy_decode(model, src_test, max_len=SEQ_LEN + 2)

        # Hedef çıktıya SOS tokenını ekleyip karşılaştırılabilir hale getir
        # greedy_decode SOS ile başladığı için tgt_output_test'e de ekliyoruz.
        tgt_with_sos = torch.cat(
            [torch.full((batch_size, 1), SOS, dtype=torch.long), tgt_output_test], dim=1
        )

        # Tahmin ve gerçek değerlerin uzunluklarını eşitlemek için pad veya kesme yap
        max_len_pred = predictions.size(1)
        max_len_tgt = tgt_with_sos.size(1)

        # En uzun diziye göre padleme veya kesme yap
        if max_len_pred > max_len_tgt:
            # Tahmin daha uzunsa hedefi padle
            padded_tgt = F.pad(tgt_with_sos, (0, max_len_pred - max_len_tgt), 'constant', PAD)
            padded_predictions = predictions
        elif max_len_tgt > max_len_pred:
            # Hedef daha uzunsa tahmini padle
            padded_predictions = F.pad(predictions, (0, max_len_tgt - max_len_pred), 'constant', PAD)
            padded_tgt = tgt_with_sos
        else:
            padded_predictions = predictions
            padded_tgt = tgt_with_sos

        # EOS tokenından sonrası önemsiz olduğu için karşılaştırmayı yapay olarak durdurabiliriz
        # Ancak 'copy' görevi olduğu için tüm dizinin doğru olması idealdir.
        # Basitlik için direk tüm diziyi karşılaştırıyorum.

        # Tam dizi eşleşmesini kontrol et
        batch_correct = (padded_predictions == padded_tgt).all(dim=1).sum().item()
        correct_predictions += batch_correct
        total_predictions += batch_size

    accuracy = correct_predictions / total_predictions
    print(f"Test setinde doğruluk: {accuracy:.4f} ({correct_predictions}/{total_predictions})\n")

